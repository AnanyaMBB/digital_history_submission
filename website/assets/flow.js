/* ============================================================
   INFORMATION-FLOW SEQUENCE + ACCESS-NETWORK GRAPH
   Driven by window.FLOW_DATA and window.ACCESS_NETWORK
   (generated by src/v7_flow_network.py -> assets/flow-data.js)
   ============================================================ */
(function(){
  "use strict";

  /* ---------------- INFORMATION-FLOW SEQUENCE ---------------- */
  function initFlow(){
    var root = document.getElementById('flow-seq');
    if(!root || !window.FLOW_DATA) return;
    var data = window.FLOW_DATA;
    var order = ['1847','1857','1866','1873','1890','1907','1914'];
    var pills = root.querySelector('#fs-pills');
    var rail = root.querySelector('#fs-rail');
    var yearEl = root.querySelector('#fs-year');
    var nameEl = root.querySelector('#fs-name');
    var modeEl = root.querySelector('#fs-mode');
    var spanEl = root.querySelector('#fs-span');

    order.forEach(function(id){
      if(!data[id]) return;
      var b = document.createElement('button');
      b.className = 'fs-pill';
      b.setAttribute('data-id', id);
      b.textContent = id;
      b.addEventListener('click', function(){ select(id); });
      pills.appendChild(b);
    });

    function select(id){
      var c = data[id];
      if(!c) return;
      pills.querySelectorAll('.fs-pill').forEach(function(p){
        p.classList.toggle('active', p.getAttribute('data-id')===id);
      });
      yearEl.textContent = c.year;
      nameEl.textContent = c.label;
      modeEl.textContent = c.mode;

      rail.innerHTML = '';
      var maxGap = 0;
      c.steps.forEach(function(s){ if(s.gap!=null && s.gap>maxGap) maxGap = s.gap; });

      c.steps.forEach(function(s, i){
        if(i>0){
          var link = document.createElement('div');
          link.className = 'fs-link';
          var g = (s.gap==null) ? '' : ('+' + s.gap + (s.gap===1?' day':' days'));
          if(s.gap!=null && maxGap>0 && s.gap >= 0.6*maxGap) link.classList.add('big');
          link.innerHTML = '<span class="fs-gap">'+g+'</span><span class="fs-arrow"></span>';
          rail.appendChild(link);
        }
        var node = document.createElement('div');
        node.className = 'fs-node t-' + s.tier;
        var ord = (s.kind==='public') ? 'PUBLIC' : ('STEP ' + (i+1));
        var ex = s.exemplar ? '<span class="fs-ex">'+s.exemplar+'</span>' : '';
        node.innerHTML =
          '<span class="fs-ord">'+ord+'</span>'+
          '<span class="fs-actor">'+s.actor+'</span>'+ ex +
          '<span class="fs-date">'+s.date+'</span>';
        rail.appendChild(node);
      });

      if(c.span_days!=null){
        spanEl.innerHTML = 'First actor to public rupture: <b>'+c.span_days+' days</b>';
      } else { spanEl.textContent=''; }
    }

    select('1866');
  }

  /* ---------------- ACCESS NETWORK GRAPH ---------------- */
  function initNetwork(){
    var root = document.getElementById('access-net');
    if(!root || !window.ACCESS_NETWORK) return;
    var net = window.ACCESS_NETWORK;
    var svg = root.querySelector('#an-svg');
    var rankEl = root.querySelector('#an-rank');
    var detailEl = root.querySelector('#an-detail');
    var statsEl = root.querySelector('#an-stats');
    var W = 640, H = 560, PAD = 60;
    var SVGNS = 'http://www.w3.org/2000/svg';

    // stat strip
    var s = net.summary;
    var stats = [
      {v:s.n_institutions, l:'named institutions'},
      {v:s.n_edges, l:'co-appearance links'},
      {v:Math.round(s.core_share*100)+'%', l:'are discount houses (the core)'},
      {v:s.most_central, l:'most central node · eig '+s.most_central_eig, small:true}
    ];
    stats.forEach(function(st){
      var d = document.createElement('div');
      d.className = 'an-stat';
      d.innerHTML = '<div class="v"'+(st.small?' style="font-size:19px;line-height:1.1"':'')+'>'+st.v+'</div><div class="l">'+st.l+'</div>';
      statsEl.appendChild(d);
    });

    // scale spring-layout coords (roughly -1..1) into the viewbox
    var xs = net.nodes.map(function(n){return n.x;});
    var ys = net.nodes.map(function(n){return n.y;});
    var minX=Math.min.apply(null,xs), maxX=Math.max.apply(null,xs);
    var minY=Math.min.apply(null,ys), maxY=Math.max.apply(null,ys);
    function sx(x){ return PAD + (x-minX)/(maxX-minX||1)*(W-2*PAD); }
    function sy(y){ return PAD + (y-minY)/(maxY-minY||1)*(H-2*PAD); }
    var byId = {};
    net.nodes.forEach(function(n){ byId[n.id]=n; });
    var maxEig = Math.max.apply(null, net.nodes.map(function(n){return n.eig;}));

    // edges first
    var edgeEls = [];
    net.edges.forEach(function(e){
      var a=byId[e.a], b=byId[e.b];
      if(!a||!b) return;
      var ln = document.createElementNS(SVGNS,'line');
      ln.setAttribute('x1', sx(a.x)); ln.setAttribute('y1', sy(a.y));
      ln.setAttribute('x2', sx(b.x)); ln.setAttribute('y2', sy(b.y));
      ln.setAttribute('class','an-edge');
      ln.setAttribute('stroke-width', (0.5 + 0.8*e.w).toFixed(2));
      ln.setAttribute('opacity', 0.4);
      ln.setAttribute('data-a', e.a); ln.setAttribute('data-b', e.b);
      svg.appendChild(ln);
      edgeEls.push(ln);
    });

    // nodes
    net.nodes.forEach(function(n){
      var g = document.createElementNS(SVGNS,'g');
      g.setAttribute('class','an-node');
      g.setAttribute('data-id', n.id);
      g.setAttribute('transform','translate('+sx(n.x)+','+sy(n.y)+')');
      var r = 7 + 22*(n.eig/(maxEig||1));
      var c = document.createElementNS(SVGNS,'circle');
      c.setAttribute('r', r.toFixed(1));
      c.setAttribute('fill', n.color);
      g.appendChild(c);
      var t = document.createElementNS(SVGNS,'text');
      t.setAttribute('text-anchor','middle');
      t.setAttribute('y', (r+10).toFixed(1));
      // shorten very long labels for the canvas
      t.textContent = n.id.length>22 ? n.id.slice(0,20)+'…' : n.id;
      g.appendChild(t);
      g.addEventListener('mouseenter', function(){ highlight(n.id); });
      g.addEventListener('click', function(){ highlight(n.id, true); });
      svg.appendChild(g);
    });

    function highlight(id, lock){
      svg.querySelectorAll('.an-node').forEach(function(g){
        g.classList.toggle('sel', g.getAttribute('data-id')===id);
      });
      edgeEls.forEach(function(ln){
        var on = ln.getAttribute('data-a')===id || ln.getAttribute('data-b')===id;
        ln.classList.toggle('lit', on);
        ln.setAttribute('opacity', on ? 1 : 0.18);
      });
      rankEl.querySelectorAll('li').forEach(function(li){
        li.classList.toggle('sel', li.getAttribute('data-id')===id);
      });
      showDetail(id);
    }

    function showDetail(id){
      var n = byId[id];
      if(!n) return;
      detailEl.innerHTML =
        '<div class="d-name">'+n.id+'</div>'+
        '<div class="d-type">'+n.type+'</div>'+
        '<div class="d-row"><span>Eigenvector centrality</span><span>'+n.eig.toFixed(3)+'</span></div>'+
        '<div class="d-row"><span>Crisis periods present</span><span>'+n.n_periods+'</span></div>'+
        '<div class="d-row"><span>Co-appearance degree</span><span>'+n.degree+'</span></div>'+
        '<div class="d-lab" style="margin-top:14px">Appears in</div>'+
        '<div class="d-periods">'+n.periods.map(function(p){return '<span>'+p+'</span>';}).join('')+'</div>';
    }

    // ranked list (top 7 by eigenvector centrality)
    var ranked = net.nodes.slice().sort(function(a,b){ return b.eig-a.eig; }).slice(0,7);
    ranked.forEach(function(n){
      var li = document.createElement('li');
      li.setAttribute('data-id', n.id);
      li.innerHTML =
        '<span class="dot" style="background:'+n.color+'"></span>'+
        '<span class="nm">'+n.id+'</span>'+
        '<span class="sc">'+n.eig.toFixed(2)+'</span>';
      li.addEventListener('mouseenter', function(){ highlight(n.id); });
      li.addEventListener('click', function(){ highlight(n.id, true); });
      rankEl.appendChild(li);
    });

    highlight(s.most_central, true);
  }

  function init(){ initFlow(); initNetwork(); }
  if(document.readyState==='loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
